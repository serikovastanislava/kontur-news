IMPORTANT_WORDS = [
    "срочно", "важно", "экстренно", "чрезвычай", "погиб", "погибли", "взрыв", "пожар",
    "землетряс", "авари", "санкц", "президент", "правительств", "войн", "атака", "обстрел",
    "угроз", "заявил", "решение", "ставк", "выбор", "закон", "чп",
]


def classify_news(title: str, content: str = "") -> tuple[str, int]:
    text = re.sub(r"\s+", " ", f"{title} {content}").lower()
    scores = {category: 0 for category in CATEGORY_RULES}
    for category, words in CATEGORY_RULES.items():
        for word in words:
            if word in text:
                scores[category] += 1
    category = max(scores, key=scores.get) if any(scores.values()) else "Мир"
    importance = min(100, sum(8 for word in IMPORTANT_WORDS if word in text) + scores[category] * 3)
    return category, importance
